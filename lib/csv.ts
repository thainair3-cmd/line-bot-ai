// Pure CSV helpers (no imports), shared by the FAQ and product sheets and loadable by tests.

/**
 * Minimal RFC 4180 CSV parser: handles quoted fields containing commas,
 * newlines and escaped quotes (""), plus CRLF line endings.
 */
export function parseCsv(input: string): string[][] {
  const text = input.replace(/^﻿/, "");
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let inQuotes = false;

  for (let i = 0; i < text.length; i++) {
    const ch = text[i];

    if (inQuotes) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += ch;
      }
      continue;
    }

    if (ch === '"') {
      inQuotes = true;
    } else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += ch;
    }
  }

  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  return rows;
}

/** Lowercase and drop all whitespace (and any BOM) so " Question " / "คำ ถาม" still match. */
export function normalizeHeader(h: string): string {
  return h.replace(/﻿/g, "").replace(/\s+/g, "").toLowerCase();
}
